def build():
    out=[]; n_tok=0
    for domain, spaces in SPACES.items():
        for name, toks in spaces.items():
            n=len(toks); arr=[]
            for i,t in enumerate(toks):
                pos=i*5/max(n-1,1)          # 相对位置映射到 0-5 bins
                tw=0.2+0.8*(i/(n-1) if n>1 else 1.0)
                alpha=[round(1+4*math.exp(-((pos-(b-0.5))**2)/0.6),3) for b in range(1,6)]
                arr.append({"token":t,"time_weight":round(tw,3),"alpha":alpha})
                n_tok+=1
            out.append({"concept_space":name,"domain":domain,"tokens":arr})
    return {"kind":"concept-atlas-module1","n_spaces":len(out),"n_tokens":n_tok,
            "rule":"time_weight 单调递增 (i/(n-1)); alpha=5-bin Dirichlet 浓度 (高斯鼓包于自身位)",
            "source":"模块一 docx sha 61e17591… · 园区语料与西园叙事人物志",
            "spaces":out}

