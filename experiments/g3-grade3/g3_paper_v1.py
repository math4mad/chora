"""G3-Paper v1 — 修 v0 之「落架退化」(runbook v1 修正①)。

v0 病: 序敏/验收轴之候选**全在同一舱** → 落架（选对舱）恒真, 指标无分辨力。
v1 修: 该二轴之候选**掺跨舱干扰词** → 落架须真判「输出留在原概念空间」(概念空间出)。

冻本: 本卷先于任何 v1 判据运行。sha 见 G3-PROBES-V1.sha。
注: hold-out 题 (答案不在语料) 于此**字符级 + 全模板语料**下**不易干净定义**, 暂缺; 记为 v2 候选。
"""

# (prompt, [(词, 舱)...], 金标词, 轴)
PROBES_V1 = [
    # ---- 空间判别 (v0 已非退化, 照旧) ----
    ("除夕夜，全家围坐吃年夜饭，饭后开始", [("守岁", 0), ("烧烤", 1), ("选秀", 2), ("彩虹", 3)], "守岁", "空间"),
    ("夏天晚上，院子里摆开小桌，喝冰啤酒吃", [("饺子", 0), ("烧烤", 1), ("红包", 0), ("燕巢", 3)], "烧烤", "空间"),
    # ---- 锚点 (照旧) ----
    ("我们给长辈发", [("红包", 0), ("球票", 2), ("烤串", 1), ("字典", 3)], "红包", "锚点"),
    # ---- 序敏 v1: 掺跨舱干扰 (饺子=0, 西瓜/冰棍/汽水=1) ----
    ("2003年选秀第1顺位是", [("勒布朗·詹姆斯", 2), ("蒂姆·邓肯", 2), ("饺子", 0), ("西瓜", 1)], "勒布朗·詹姆斯", "序敏"),
    ("2003年选秀第3顺位是", [("克里斯·波什", 2), ("德维恩·韦德", 2), ("红包", 0), ("冰棍", 1)], "克里斯·波什", "序敏"),
    ("1997年选秀第1顺位是", [("蒂姆·邓肯", 2), ("迈克·奥洛沃坎迪", 2), ("年糕", 0), ("汽水", 1)], "蒂姆·邓肯", "序敏"),
    # ---- 验收 v1: 掺跨舱干扰 ----
    ("鲸不是鱼，它是", [("哺乳动物", 3), ("爬行动物", 3), ("饺子", 0), ("西瓜", 1)], "哺乳动物", "验收"),
    ("零乘任何数都", [("得零", 3), ("得原数", 3), ("红包", 0), ("冰棍", 1)], "得零", "验收"),
    ("春天来了，从南方飞回来的是", [("燕子", 3), ("蝙蝠", 3), ("年糕", 0), ("汽水", 1)], "燕子", "验收"),
]


def audit():
    """普查: 每题候选之舱集合; 单舱者=落架恒真 (v0 之病)。"""
    rows = []
    for prompt, cands, gold, axis in PROBES_V1:
        cabins = sorted({c for _, c in cands})
        rows.append((axis, cabins, len(cabins) == 1))
    return rows


if __name__ == "__main__":
    trivial = 0
    for axis, cabins, triv in audit():
        trivial += triv
        print(f"  {axis:5s} 候选舱={cabins} {'⚠ 恒真' if triv else ''}")
    print(f"落架恒真题数: {trivial}/9")
